function createRoom(hotelId, name, price, category = 'standard', capacity = 2) {
  return {
    id: `${hotelId}-room-1`,
    name,
    description: 'Quarto confortavel com cama casal, ar-condicionado e banheiro privativo.',
    category,
    price,
    capacity,
    size: category === 'luxury' ? 42 : 28,
    amenities: ['wifi', 'air-conditioning', 'room-service'],
    images: ['https://images.unsplash.com/photo-1631049307264-da0ec9d70304?w=800'],
    available: true,
  }
}

function createReview(id, userName, rating = 5) {
  return {
    id: `dummy-review-${id}`,
    userId: '',
    userName,
    rating,
    comment: 'Hospedagem excelente, equipe atenciosa e localizacao muito boa.',
    date: '2026-04-12',
    stayDate: '2026-04-06',
  }
}

function createHotel({
  id,
  name,
  slug,
  city,
  state,
  address,
  latitude,
  longitude,
  stars,
  rating,
  reviewCount,
  priceFrom,
  image,
  amenities,
  roomName,
  roomCategory,
}) {
  return {
    id: `dummy-${id}`,
    name,
    slug,
    description: `${name} e uma hospedagem ficticia criada para demonstracao do Viajei, com boa localizacao em ${city} e estrutura para lazer e trabalho.`,
    shortDescription: `Hospedagem completa em ${city}`,
    address,
    city,
    state,
    country: 'Brasil',
    zipCode: '00000-000',
    latitude,
    longitude,
    stars,
    rating,
    reviewCount,
    priceFrom,
    images: [
      {
        url: image,
        alt: `Imagem de ${name}`,
        category: 'exterior',
      },
    ],
    amenities,
    rooms: [createRoom(`dummy-${id}`, roomName, priceFrom, roomCategory, stars >= 5 ? 4 : 2)],
    reviews: [createReview(id, 'Hospede verificado', Math.round(rating))],
    policies: defaultPolicies,
    contact: {
      phone: '(11) 4000-0000',
      email: `reservas@${slug}.local`,
      website: `${slug}.local`,
    },
  }
}

